// Converts RPCS3-decompiled RSX programs from rpcs3_unique_shaders.txt into GLSL ES 3.00.
// Usage: node rpcs3dump2glsl.mjs <dump.txt> <SpirvFileName> <out.glsl> [vs|fs] [constantCount]
// Vertex inputs: read_location(0) -> aPos, 8 -> aTc0, 11 -> aTc3. Constants: _fetch_constant(i) -> vc[i] / fc[i],
// filled by the caller in RPCS3's compacted order (the same order the RenderDoc capture shows).
import { readFileSync, writeFileSync } from 'node:fs';

const [dumpPath, fileName, outPath, kind, countArg] = process.argv.slice(2);
const dump = readFileSync(dumpPath, 'utf8');
const sections = dump.split(/^=+$/m);
const section = sections.find((s) => s.includes(`'${fileName}'`));
if (!section) throw new Error(`${fileName} not found`);

// GLSL ES has no scalar swizzles: SCALARFN(args).xxxx -> vec4(SCALARFN(args)). Only functions that
// return a float are rewritten; vector expressions such as _fetch_constant(i).xxxx stay as they are.
const SCALAR_FNS = new Set(['sqrt', 'inversesqrt', '_builtin_log2', '_builtin_rsq', '_builtin_rcp']);
function fixScalarSwizzles(src) {
  let out = src, from = 0, idx;
  while ((idx = out.indexOf(').xxxx', from)) >= 0) {
    let depth = 0, i = idx;
    for (; i >= 0; i--) {
      if (out[i] === ')') depth++;
      else if (out[i] === '(' && --depth === 0) break;
    }
    let s = i;
    while (s > 0 && /[A-Za-z0-9_]/.test(out[s - 1])) s--;
    if (!SCALAR_FNS.has(out.slice(s, i))) { from = idx + 6; continue; }
    out = out.slice(0, s) + 'vec4(' + out.slice(s, idx + 1) + ')' + out.slice(idx + 6);
    from = s;
  }
  return out;
}

const body = (name) => {
  const start = section.indexOf(`void ${name}()`);
  const open = section.indexOf('{', start);
  let depth = 0, i = open;
  for (; i < section.length; i++) {
    if (section[i] === '{') depth++;
    else if (section[i] === '}' && --depth === 0) break;
  }
  return section.slice(open + 1, i);
};

const regs = Array.from({ length: 16 }, (_, i) => `r${i}`).concat(Array.from({ length: 16 }, (_, i) => `h${i}`));
const helpers = `
#define fma(a, b, c) ((a) * (b) + (c))
#define CMP_FIXUP(x) (x)
float _select(float a, float b, bool c) { return c ? b : a; }
vec4 _select(vec4 a, vec4 b, bvec4 c) { return mix(a, b, vec4(c)); }
`;
const count = Number(countArg) || 32;
let glsl;

if (kind === 'vs') {
  let src = body('vs_main')
    .replace(/^.*xform_constants_offset.*$/m, '')
    .replace(/read_location\(0\)/g, 'aPos').replace(/read_location\(8\)/g, 'aTc0').replace(/read_location\(11\)/g, 'aTc3');
  src = fixScalarSwizzles(src);
  const mainText = section.slice(section.indexOf('void main ()'));
  const outs = [...mainText.matchAll(/(tc\d) = (dst_reg\d+);/g)].map((m) => [m[1], m[2]]);
  const dsts = [...new Set([...src.matchAll(/dst_reg\d+/g)].map((m) => m[0]))];
  glsl = `#version 300 es
// GENERATED by app/tools/rpcs3dump2glsl.mjs from rpcs3_unique_shaders.txt (${fileName}) - do not edit.
precision highp float;
layout(location = 0) in vec4 aPos;   // in_pos
layout(location = 1) in vec4 aTc0;   // in_tc0
layout(location = 2) in vec4 aTc3;   // in_tc3
uniform vec4 vc[${count}];
#define _fetch_constant(i) vc[i]
${outs.map(([t]) => `out vec4 ${t};`).join('\n')}
${helpers}
${dsts.map((d) => `vec4 ${d} = vec4(0.0, 0.0, 0.0, 1.0);`).join('\n')}

void vs_main() {${src}}

void main() {
  vs_main();
  gl_Position = dst_reg0;
${outs.map(([t, d]) => `  ${t} = ${d};`).join('\n')}
}
`;
} else {
  let src = body('fs_main')
    .replace(/^.*const sampler_info.*$/gm, '')
    .replace(/TEX2D\((\d+), /g, 'texture(sTex$1, ')
    .replace(/\/\/ FENC[BT]/g, '');
  src = fixScalarSwizzles(src);
  const samplers = [...new Set([...src.matchAll(/sTex(\d+)/g)].map((m) => m[1]))];
  const ins = [...new Set([...src.matchAll(/\btc(\d)\b/g)].map((m) => `tc${m[1]}`))].sort();
  glsl = `#version 300 es
// GENERATED by app/tools/rpcs3dump2glsl.mjs from rpcs3_unique_shaders.txt (${fileName}) - do not edit.
precision highp float;
${ins.map((t) => `in vec4 ${t};`).join('\n')}
${samplers.map((s) => `uniform sampler2D sTex${s};`).join('\n')}
uniform vec4 fc[${count}];
#define _fetch_constant(i) fc[i]
out vec4 oColor;
${helpers}
vec4 _builtin_divsq(vec4 a, float b) { return a * inversesqrt(b); }
float _builtin_divsq(float a, float b) { return a * inversesqrt(b); }
vec4 _builtin_div(vec4 a, float b) { return a / b; }
float _builtin_div(float a, float b) { return a / b; }
float _builtin_rsq(float a) { return inversesqrt(a); }
float _builtin_rcp(float a) { return 1.0 / a; }
float _builtin_log2(float a) { return log2(a); }
vec4 precision_clamp(vec4 a, float lo, float hi) { return clamp(a, lo, hi); }
vec4 clamp16(vec4 a) { return clamp(a, -65504.0, 65504.0); }
vec4 _saturate(vec4 a) { return clamp(a, 0.0, 1.0); }
${regs.map((r) => `vec4 ${r} = vec4(0.0);`).join('\n')}

void fs_main() {${src}}

void main() {
  fs_main();
  oColor = r0;
}
`;
}
writeFileSync(outPath, glsl);
console.log('wrote', outPath);
