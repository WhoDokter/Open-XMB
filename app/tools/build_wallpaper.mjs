// ---------------------------------------------------------------------------------------------------
// Modules: each ES module becomes an async factory; imports await the dependency's factory.
// Handles exactly the syntax used in app/src (named imports, export function/class/const/let).
// ---------------------------------------------------------------------------------------------------
function splitTopLevel(text) {
  const parts = []; let depth = 0, start = 0, quote = null;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) { if (c === quote && text[i - 1] !== '\\') quote = null; continue; }
    if (c === '"' || c === "'" || c === '`') quote = c;
    else if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) depth--;
    else if (c === ',' && depth === 0) { parts.push(text.slice(start, i)); start = i + 1; }
  }
  parts.push(text.slice(start));
  return parts;
}

function transformModule(name, src) {
  const deps = [], exportsList = [];
  const dir = name.includes('/') ? name.slice(0, name.lastIndexOf('/') + 1) : '';   // imports resolve from here
  let out = src.replace(/^import\s*\*\s*as\s+(\w+)\s+from\s*'\.\/([\w./]+)';?/gm, (_, ns, d) => {
    deps.push(dir + d);
    return `const ${ns} = await __req('${dir + d}');`;
  });
  out = out.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w./]+)';?/gm, (_, names, d) => {
    const dep = dir + d;
    deps.push(dep);
    const binds = names.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ': '));
    return `const { ${binds.join(', ')} } = await __req('${dep}');`;
  });
  if (/^\s*import\s/m.test(out)) throw new Error(`${name}: unsupported import`);
  out = out.replace(/^export\s+(async\s+function|function|class)\s+(\w+)/gm, (_, kw, id) => { exportsList.push(id); return `${kw} ${id}`; });
  out = out.replace(/^export\s+(const|let)\s+/gm, (m, kw, offset) => {
    // collect every declarator name of this statement (up to the first top-level ';')
    let depth = 0, end = offset;
    for (let i = offset + m.length; i < out.length; i++) {
      const c = out[i];
      if ('([{'.includes(c)) depth++; else if (')]}'.includes(c)) depth--;
      else if (c === ';' && depth === 0) { end = i; break; }
    }
    for (const decl of splitTopLevel(out.slice(offset + m.length, end))) exportsList.push(decl.trim().match(/^(\w+)/)[1]);
    return `${kw} `;
  });
  if (/^export\s/m.test(out)) throw new Error(`${name}: unsupported export`);
  const ret = exportsList.map((id) => `get ${id}() { return ${id}; }`).join(', ');
  return { deps, code: `__mods[${JSON.stringify(name)}] = async function () {\n${out}\nreturn { ${ret} };\n};\n` };
}

function collectModules(entry) {
  const seen = new Map(), order = [];
  const visit = (name) => {
    if (seen.has(name)) return;
    const m = transformModule(name, readFileSync(join(APP, 'src', name), 'utf8'));
    seen.set(name, m);
    m.deps.forEach(visit);
    order.push(name);
  };
  visit(entry);
  return order.map((n) => seen.get(n).code).join('\n');
}

// ---------------------------------------------------------------------------------------------------
// Embedded files, keyed by the URL path the app requests (resolved against /app/, like index.html)
// ---------------------------------------------------------------------------------------------------
const files = {};
const addFile = (url, path, kind) => {
  const key = new URL(url, 'http://xmb/app/').pathname;
  const data = readFileSync(path);
  files[key] = kind === 'text' ? { t: 'text', d: data.toString('utf8') } : { t: kind, d: data.toString('base64') };
};
for (const f of readdirSync(join(APP, 'src', 'shaders'))) {
  if (!f.endsWith('.glsl')) continue;
  const path = join(APP, 'src', 'shaders', f);
  if (ASSETS === 'procedural' && firmwareShader(readFileSync(path, 'utf8'))) continue;
  addFile(`./src/shaders/${f}`, path, 'text');
}
if (ASSETS === 'extracted') {
  for (const f of MNU_BASE) addFile(`../extracted_lines/${f}.mnu`, join(ROOT, 'extracted_lines', `${f}.mnu`), 'bin');
  for (const p of PRESETS) for (const f of MNU_OVERRIDE) {
    const path = join(ROOT, 'extracted_lines', 'override', p, `${f}.mnu`);
    if (existsSync(path)) addFile(`../extracted_lines/override/${p}/${f}.mnu`, path, 'bin');
  }
  const pngs = ['proc_iridescent.png'];
  for (let i = 1; i <= 12; i++) { const n = String(i).padStart(2, '0'); pngs.push(`month_day_${n}.png`, `month_night_${n}.png`); }
  for (const f of pngs) addFile(`../assets/png/${f}`, join(ROOT, 'assets', 'png', f), 'png');
  addFile('../assets/lines/freslut_512x1.bin', join(ROOT, 'assets', 'lines', 'freslut_512x1.bin'), 'bin');
  addFile('../assets/tables/spline_tables.bin', join(ROOT, 'assets', 'tables', 'spline_tables.bin'), 'bin');
}

